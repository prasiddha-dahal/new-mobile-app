/// User domain entity (pure Dart, no JSON/Flutter deps).
class User {
  const User({
    required this.id,
    required this.name,
    required this.email,
    required this.role,
    this.city,
    this.phone,
    this.specialty,
    required this.status,
    this.photo,
    this.mustChangePassword = false,
  });

  final String id;
  final String name;
  final String email;
  final String role;
  final String? city;
  final String? phone;
  final String? specialty;
  final String status;

  /// Absolute or API-relative URL of the profile photo. Null for most accounts —
  /// screens fall back to a placeholder rather than an invented avatar.
  final String? photo;

  /// True for therapists whose password was generated by the approval step.
  final bool mustChangePassword;

  bool get isPatient => role.toUpperCase() == 'PATIENT';
  bool get isTherapist => role.toUpperCase() == 'THERAPIST';
  bool get isAdmin => role.toUpperCase() == 'ADMIN';
  bool get isApproved => status.toUpperCase() == 'APPROVED';
  bool get isPending => status.toUpperCase() == 'PENDING';
  bool get isRejected => status.toUpperCase() == 'REJECTED';

  /// Route this user should land on after authentication.
  String get homeRoute {
    if (isTherapist) return isApproved ? '/therapist/home' : '/verify-pending';
    return '/patient/home';
  }

  /// Initials used by avatar fallbacks.
  String get initials {
    final parts = name
        .trim()
        .split(RegExp(r'\s+'))
        .where((p) => p.isNotEmpty)
        .toList();
    if (parts.isEmpty) return '?';
    if (parts.length == 1) return parts.first[0].toUpperCase();
    return (parts.first[0] + parts.last[0]).toUpperCase();
  }

  User copyWith({
    String? name,
    String? city,
    String? phone,
    String? specialty,
    String? status,
    String? photo,
  }) => User(
    id: id,
    name: name ?? this.name,
    email: email,
    role: role,
    city: city ?? this.city,
    phone: phone ?? this.phone,
    specialty: specialty ?? this.specialty,
    status: status ?? this.status,
    photo: photo ?? this.photo,
    mustChangePassword: mustChangePassword,
  );
}

/// Result of a successful authentication.
///
/// [accessToken] is nullable: a therapist signup returns a user without a token
/// because the account cannot sign in until an admin approves the application.
class AuthTokens {
  const AuthTokens({required this.accessToken, required this.user});

  final String? accessToken;
  final User user;

  bool get hasToken => accessToken != null && accessToken!.isNotEmpty;
}
